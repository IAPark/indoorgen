#!/usr/bin/env python3
"""rule_table.py: rules/RULES.md from rules/layout.json, and what the old passes still hold for the rooms not yet ported."""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(f"{R}/rules/layout.json"))
T = {0: "must", 1: "should", 2: "may"}
def place(p):
    if p == "wall": return "back to a wall"
    k, v = next(iter(p.items()))
    if k == "beside": return f"beside `{v['parent']}`, {'+' if v['side'] > 0 else '-'}y side"
    if k == "hang": return "on a wall, centre " + "/".join(f"{c} m" for c in v.get("centers", [])) + (f"; {v['tall_from']} m+ tall: bottom at {v['tall_bottom']} m" if "tall_from" in v else "")
    if k == "over": return f"over `{v['parent']}`: centre {v['center']} m, at least {v['gap']} m above it"
    if k == "under": return f"under `{v['parent']}`: its width + {v['add_w']} m, {v['share']} of its length, {v['past']} m past its foot"
    return k
out = ["# Layout rules", "", "Generated by `tools/rule_table.py` from `rules/layout.json`. Edit the JSON; `lay --watch` re-solves with no rebuild.", "",
       "Tiers: **must** (the room fails without it), **should** (a miss is reported), **may** (left out freely). Rigid parts block walkways and doors. Soft parts may overlap furniture and door clearances and may be walked through, unless `soft blocks`.", ""]
for room, rr in d.items():
    out += [f"## {room}", "", "| Item | Class | Tier | Chance | From m² | Placement | Limits | Fallbacks | Scored by |", "|---|---|---|---|---|---|---|---|---|"]
    for i in rr["program"]:
        lim = []
        if i.get("front"): lim.append(f"front {i['front']} m free")
        if i.get("avoid_window"): lim.append("not before a window")
        if i.get("reach"): lim.append("walk reaches it")
        if i.get("min_door"): lim.append(f"door ≥ {i['min_door']} m")
        if i.get("cover"): lim.append("under furniture")
        if i.get("soft_blocks"): lim.append("soft blocks")
        if i.get("unless"): lim.append("only without " + ", ".join(i["unless"]))
        f = i.get("fit", {})
        for k, n in (("max_w", "width"), ("max_h", "height"), ("max_d", "depth")):
            if k in f: lim.append(f"{n} ≤ {f[k]} m")
        var = []
        for v in i.get("variants", [])[1:]:
            s = v["piece"].replace("as_is", "")
            if v.get("width"): s += f" {v['width']} m wide"
            if v.get("side"): s += " side to wall"
            if v.get("over_window"): s += " before window"
            var.append(s.strip())
        out.append(f"| {i['id']} | {i['class'].replace('Factory','')} | {T[i.get('tier',0)]} | {i.get('chance',1)} | {i.get('min_area') or ''} | {place(i['place'])} | {'; '.join(lim)} | {', '.join(var)} | {', '.join(t['name'] + ' ' + str(t.get('w',1)) for t in i.get('terms',[]))} |")
    out.append("")
out += ["## Not ported yet", "", "From `LayoutRules` (reviewed values, which keep their numbers), `groups::cap` and `realism.rs`:", "",
 "| Room | Rules to carry over |", "|---|---|",
 "| Living room | One TV and stand; sofa facing it, 1.3–4.0 m (backed to a side wall up to 3.6, floating 2.2–3.8); armchairs: one from 20 m², two from 30 m²; coffee table 0.75 of sofa width; bookcase on a free wall from 20 m² without built-ins; one plant below 20 m²; storage capped per room; 2 pictures |",
 "| Dining room | Table centred, 0.75 m from walls and 1.0 from doors; 1 m table under the small-room size; round chance for tables to 1.6 m; chairs 0.6 m apart, tucked 0.04, end chairs from 1.2 m; sideboard on a free wall; tall cabinet from 18 m²; rug; plant; 1 picture |",
 "| Kitchen | L template with fridge and range at the leg ends; up to 3 extra runs; aisle 1.0 m; sink to range 0.6 m; fridge door clear 0.2 m; 1.0 m before a range or dishwasher; fridge corner gap 0.3 m; slots under 0.6 m closed; triangle legs 1.2–2.7 m, sum 4–8 m; one fridge, oven, dishwasher |",
 "| Utility | Up to 2 storage pieces |",
 "| All | Windows as solver variables (still fixed); built-ins; items on surfaces and shelf fill; re-planning when a must fails |", "",
 "Infinigen's `home.py` terms to check against: " + open(os.path.expanduser("~/work/bench/lay/home_terms.txt")).read().strip(), ""]
open(f"{R}/rules/RULES.md", "w").write("\n".join(out))
print(f"{R}/rules/RULES.md", len(out))
